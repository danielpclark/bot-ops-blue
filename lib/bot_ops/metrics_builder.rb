# frozen_string_literal: true

module BotOps
  # Builds lib/bot_ops/font_metrics.rb: the advance width of every printable
  # ASCII character (and a few symbols the UI uses) in each bundled font, in
  # ems, read straight from the TrueType tables (cmap format 4, hmtx). Ruby
  # lays text out by width (clipping, placing a note after a number) without
  # asking the native side. Run with `rake metrics` after changing fonts.
  module MetricsBuilder
    FONTS = {
      normal: "Inter-Regular.ttf", medium: "Inter-Medium.ttf", semibold: "Inter-SemiBold.ttf",
      bold: "Inter-Bold.ttf", display: "Montserrat-ExtraBold.ttf", mono: "DejaVuSansMono.ttf"
    }.freeze
    DIR = File.expand_path("../../ext/bot_ops_native/fonts", __dir__)
    PATH = File.expand_path("font_metrics.rb", __dir__)
    CHARS = ((32..126).map(&:chr) + %w[· … › ‹ — – ↗ ● ○ ✓]).freeze

    module_function

    def build
      tables = FONTS.to_h { |k, file| [k, widths(File.binread(File.join(DIR, file)))] }
      body = tables.map do |k, w|
        pairs = CHARS.map { |ch| "#{ch.inspect} => #{w[ch].round(4)}" }
        "    #{k}: {\n      #{pairs.each_slice(8).map { |s| s.join(', ') }.join(",\n      ")}\n    }.freeze"
      end
      File.write(PATH, <<~RUBY)
        # frozen_string_literal: true

        # GENERATED by `rake metrics` from ext/bot_ops_native/fonts. Don't edit.
        # Advance widths in ems per character, per font.
        module BotOps
          FONT_METRICS = {
        #{body.join(",\n")}
          }.freeze
        end
      RUBY
      tables.size
    end

    # { char => advance in ems } for CHARS.
    def widths(ttf)
      tables = table_directory(ttf)
      units = ttf[tables["head"] + 18, 2].unpack1("n")
      n_hmetrics = ttf[tables["hhea"] + 34, 2].unpack1("n")
      hmtx = tables["hmtx"]
      advance = lambda do |gid|
        i = [gid, n_hmetrics - 1].min
        ttf[hmtx + i * 4, 2].unpack1("n")
      end
      glyph = cmap4(ttf, tables["cmap"])
      CHARS.to_h { |ch| [ch, advance.(glyph.(ch.ord)) / units.to_f] }
    end

    def table_directory(ttf)
      count = ttf[4, 2].unpack1("n")
      (0...count).to_h do |i|
        tag, _sum, offset = ttf[12 + i * 16, 12].unpack("a4NN")
        [tag, offset]
      end
    end

    # The Unicode BMP mapping (platform 3 encoding 1, or 0/3), as code -> glyph id.
    def cmap4(ttf, cmap)
      n = ttf[cmap + 2, 2].unpack1("n")
      sub = (0...n).map { |i| ttf[cmap + 4 + i * 8, 8].unpack("nnN") }
                   .find { |pid, eid, _| [[3, 1], [0, 3], [0, 4]].include?([pid, eid]) }
      raise "no unicode cmap" unless sub
      t = cmap + sub[2]
      raise "cmap format #{ttf[t, 2].unpack1('n')}" unless ttf[t, 2].unpack1("n") == 4
      segs = ttf[t + 6, 2].unpack1("n") / 2
      ends = ttf[t + 14, segs * 2].unpack("n*")
      starts = ttf[t + 16 + segs * 2, segs * 2].unpack("n*")
      deltas = ttf[t + 16 + segs * 4, segs * 2].unpack("n*")
      range_at = t + 16 + segs * 6
      ranges = ttf[range_at, segs * 2].unpack("n*")
      lambda do |code|
        i = ends.index { |e| e >= code }
        next 0 unless i && starts[i] <= code
        if ranges[i].zero?
          (code + deltas[i]) & 0xFFFF
        else
          g = ttf[range_at + i * 2 + ranges[i] + (code - starts[i]) * 2, 2].unpack1("n")
          g.zero? ? 0 : (g + deltas[i]) & 0xFFFF
        end
      end
    end
  end
end
