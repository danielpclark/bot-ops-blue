# frozen_string_literal: true

module BotOps
  # Builds cloud/setup.sh: a claude.ai/code environment setup script that
  # installs cloud/bot-ops-report.py as a user-level hook on the session VM,
  # so every repository opened in that environment reports without anything
  # committed to it. The reporter is embedded, so the script needs no
  # download. Regenerate with `rake cloud:setup_script` after editing the
  # reporter (a test fails while the two disagree).
  module CloudSetup
    DIR = File.expand_path("../../cloud", __dir__)
    PATH = File.join(DIR, "setup.sh")
    EVENTS = %w[SessionStart UserPromptSubmit PostToolUse Notification Stop SessionEnd].freeze
    COMMAND = '[ "$CLAUDE_CODE_REMOTE" = true ] && [ -n "$BOT_OPS_URL" ] && python3 "$HOME/.claude/hooks/bot-ops-report.py" || true'

    module_function

    def script
      reporter = File.read(File.join(DIR, "bot-ops-report.py"))
      raise "reporter contains the heredoc delimiter" if reporter.include?("BOT_OPS_REPORTER")
      <<~SH
        #!/bin/bash
        # Bot Ops Blue: claude.ai/code environment setup script.
        # GENERATED by `rake cloud:setup_script` from cloud/bot-ops-report.py; don't edit by hand.
        #
        # Paste this whole file into the environment's Setup script. It installs
        # the cloud reporter as a user-level hook on the session VM, for every repo
        # opened in this environment; nothing is committed to any repository.
        # The hook only reports when CLAUDE_CODE_REMOTE=true (the cloud-session
        # marker, set on this VM and never locally; not Remote Control) and
        # BOT_OPS_URL is set; the tunnel's password is a network secret.
        # Every step is best-effort: a failure here never stops a session.

        mkdir -p "$HOME/.claude/hooks" || true
        cat > "$HOME/.claude/hooks/bot-ops-report.py" <<'BOT_OPS_REPORTER' || true
        #{reporter.chomp}
        BOT_OPS_REPORTER
        chmod 755 "$HOME/.claude/hooks/bot-ops-report.py" || true

        # Add the hook to ~/.claude/settings.json, keeping anything already there.
        python3 - <<'BOT_OPS_SETTINGS' || true
        import json, os
        path = os.path.expanduser("~/.claude/settings.json")
        try:
            with open(path) as f:
                settings = json.load(f)
        except Exception:
            settings = {}
        cmd = #{COMMAND.inspect}
        hooks = settings.setdefault("hooks", {})
        for event in #{EVENTS.inspect}:
            groups = hooks.setdefault(event, [])
            if any(h.get("command") == cmd for g in groups for h in g.get("hooks", [])):
                continue
            entry = {"hooks": [{"type": "command", "command": cmd, "timeout": 5}]}
            if event == "PostToolUse":
                entry["matcher"] = "*"
            groups.append(entry)
        with open(path, "w") as f:
            json.dump(settings, f, indent=2)
        BOT_OPS_SETTINGS

        exit 0
      SH
    end
  end
end
